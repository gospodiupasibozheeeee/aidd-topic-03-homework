from rest_framework import serializers

from dashboard.models import Share


class ShareSerializer(serializers.ModelSerializer):
    """API representation of a share.

    ``uid`` is generated by the model when a share is created manually and is
    exposed as a read-only field so that the unique constraint is never
    violated from the API.
    """

    class Meta:
        model = Share
        fields = (
            "id",
            "figi",
            "isin",
            "name",
            "ticker",
            "currency",
            "uid",
            "last_price",
            "is_trend_high",
            "updated_at",
        )
        read_only_fields = ("id", "uid", "updated_at")

    def validate_last_price(self, value):
        if value is not None and value < 0:
            raise serializers.ValidationError("Цена не может быть отрицательной.")
        return value

    def validate_ticker(self, value):
        return (value or "").strip().upper()
